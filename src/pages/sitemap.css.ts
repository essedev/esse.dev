import type { APIRoute } from 'astro';
import { fontData } from 'astro:assets';
import globalCss from '../styles/global.css?raw';
import { readTokens } from '../lib/css-tokens';

// The stylesheet of /sitemap.xml, for whoever opens it in a browser: CSS applied to XML,
// not XSLT, which Chrome removes. The colors are the site's tokens read from global.css at
// build time (a renamed token fails the build), dark by default and light from the system:
// the theme toggle cannot reach an XML document. Departure Mono is the file the Fonts API
// already serves; the rest is in the system sans, since Geist has no stable URL.
export const prerender = true;

const names = [
	'--color-bg',
	'--color-line',
	'--color-fg',
	'--color-text',
	'--color-muted',
	'--color-subtle',
	'--color-accent'
] as const;

const declarations = (tokens: Record<string, string>) =>
	names.map((name) => `\t${name}: ${tokens[name]};`).join('\n');

export const GET: APIRoute = ({ site }) => {
	const dark = readTokens(globalCss, '@theme', names);
	const light = readTokens(globalCss, ":root[data-theme='light']", names);
	const font = fontData['--font-departure']?.[0]?.src.find((s) => s.url.endsWith('.woff2'));
	if (!font) throw new Error('sitemap.css: no woff2 file for --font-departure in fontData');

	const css = `/* The sitemap in a browser. Generated by src/pages/sitemap.css.ts from global.css. */

@font-face {
	font-family: 'Departure Mono';
	src: url('${font.url}') format('woff2');
	font-weight: 400;
	font-style: normal;
	font-display: swap;
}

:root {
	color-scheme: dark;
${declarations(dark)}
	--mono: 'Departure Mono', ui-monospace, monospace;
}

@media (prefers-color-scheme: light) {
	:root {
		color-scheme: light;
${declarations(light).replace(/^/gm, '\t')}
	}
}

/* The header (::before) and the count (::after) share the first row: a counter in ::after
   has seen every <url>, and the grid lifts it next to the title. */
urlset {
	display: grid;
	grid-template-columns: minmax(0, 1fr) auto;
	align-items: baseline;
	column-gap: 1rem;
	box-sizing: border-box;
	min-height: 100vh;
	margin: 0;
	padding: clamp(1.5rem, 6vw, 4rem) clamp(1rem, 4vw, 4.5rem);
	background: var(--color-bg);
	color: var(--color-text);
	font: 400 15px/1.5 ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif;
	-webkit-font-smoothing: antialiased;
	-webkit-text-size-adjust: 100%;
	text-size-adjust: 100%;
	counter-reset: urls;
}

urlset::before,
urlset::after {
	grid-row: 1;
	padding-bottom: 1.25rem;
	font-family: var(--mono);
}

urlset::before {
	content: ${JSON.stringify(`sitemap · ${site!.host}`)};
	grid-column: 1;
	color: var(--color-fg);
	font-size: 0.9375rem;
}

urlset::after {
	content: counter(urls) ' urls';
	grid-column: 2;
	color: var(--color-subtle);
	font-size: 0.75rem;
}

url {
	counter-increment: urls;
	grid-column: 1 / -1;
	display: flex;
	flex-wrap: wrap;
	align-items: baseline;
	row-gap: 0.25rem;
	padding: 0.875rem 0;
	border-top: 1px solid var(--color-line);
	font-family: var(--mono);
}

loc {
	flex: 1 0 100%;
	color: var(--color-accent);
	font-size: 0.875rem;
	overflow-wrap: anywhere;
}

lastmod {
	margin-right: 1.5rem;
	color: var(--color-muted);
	font-size: 0.75rem;
}

/* The alternates as their codes only, on one line: en · it · x-default. */
link {
	display: inline;
	color: var(--color-subtle);
	font-size: 0.75rem;
	white-space: pre;
}

link::before {
	content: attr(hreflang);
}

link + link::before {
	content: ' · ' attr(hreflang);
}

::selection {
	background: color-mix(in srgb, var(--color-accent) 22%, transparent);
	color: var(--color-fg);
}
`;
	return new Response(css, { headers: { 'Content-Type': 'text/css; charset=utf-8' } });
};
